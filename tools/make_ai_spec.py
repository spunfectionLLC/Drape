"""drape/studio/static/js/19_ai_spec.js: the .drape format spec and the example design, for the AI designer's prompt.

    python tools/make_ai_spec.py

The page's AI designer (js/20_ai.js) sends these to the model with every request. Generated from
docs/DRAPE_FILE_FORMAT.md and docs/examples/a_line_skirt.drape so there's one source; tests/test_v37_ai.py checks the
generated file is current.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "drape" / "studio" / "static" / "js" / "19_ai_spec.js"


def source() -> str:
    spec = (ROOT / "docs" / "DRAPE_FILE_FORMAT.md").read_text(encoding="utf-8").replace("\r\n", "\n")
    example = json.loads((ROOT / "docs" / "examples" / "a_line_skirt.drape").read_text(encoding="utf-8"))
    design = example["garments"][0]["design"]
    return ("// drape studio: the .drape format spec and an example design for the AI designer (20_ai.js).\n"
            "// GENERATED by tools/make_ai_spec.py from docs/DRAPE_FILE_FORMAT.md and docs/examples/a_line_skirt.drape:\n"
            "// edit those and run it again (tests/test_v37_ai.py checks this file is current).\n"
            f"const AI_SPEC = {json.dumps(spec, ensure_ascii=False)};\n"
            f"const AI_EXAMPLE = {json.dumps(design, ensure_ascii=False, separators=(',', ':'))};\n")


if __name__ == "__main__":
    OUT.write_text(source(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
